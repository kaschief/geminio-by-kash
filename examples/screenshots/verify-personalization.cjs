// Native integration checks. Run after npm run build:
// node examples/screenshots/verify-personalization.cjs
const { _electron } = require('playwright')
const fs = require('node:fs/promises')
const { execFileSync } = require('node:child_process')
const { join } = require('node:path')
const assert = require('node:assert/strict')
const ROOT = join(__dirname, '../..')
;(async () => {
  const tmp = await fs.mkdtemp('/tmp/geminio-feature-ui-')
  const repo = join(tmp, 'elastic-demo')
  const userData = join(tmp, 'settings')
  await fs.cp(join(ROOT, 'examples/playground/line-staging'), repo, { recursive: true })
  const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' })
  const names = ['a-first.ts', 'b-second.ts', 'c-last.ts', 'd-staged.ts', 'e-staged.ts']
  for (const name of names) await fs.writeFile(join(repo, name), Array.from({ length: 180 }, (_, i) => `export const value${i} = ${i}`).join('\n') + '\n')
  git('add', '.'); git('-c', 'user.name=Demo', '-c', 'user.email=demo@example.com', 'commit', '-qm', 'Add navigation fixture')
  for (const name of names) await fs.writeFile(join(repo, name), Array.from({ length: 180 }, (_, i) => `export const value${i} = ${i + 1000}`).join('\n') + '\n')
  git('add', 'd-staged.ts', 'e-staged.ts')
  await fs.mkdir(userData)
  await fs.writeFile(join(userData, 'gitcito-settings.json'), JSON.stringify({ onboardingCompleted: true, autoFetchMinutes: 0, themeMode: 'dark', fileListView: 'path', profiles: [{ id: 'default', name: 'Demo', ai: { enabled: false } }], activeProfileId: 'default', tabs: [{ id: 'repo', kind: 'repo', name: 'Elastic Demo', repos: [{ path: repo, name: 'Elastic Demo' }], activeRepoPath: repo }], activeTabId: 'repo' }))
  await fs.writeFile(join(userData, 'gitcito-keychain.json'), JSON.stringify({ consent: 'declined', explained: true }))
  let app
  try {
    app = await _electron.launch({ args: [join(ROOT, 'out/main/index.js'), '--shot', `--user-data-dir=${userData}`], cwd: ROOT })
    const page = await app.firstWindow()
    page.on('pageerror', (err) => console.log('PAGEERROR', err.message))
    await page.waitForFunction(() => window.__shot?.ready)
    await page.evaluate((p) => window.__shot.waitForRepo(p), repo)
    await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.unmaximize(); w.setContentSize(1440, 900) })
    await page.evaluate((p) => window.__shot.repo.getState().select(p, { type: 'wip' }), repo)
    const row = (name) => page.locator(`.file-list [data-file-path="${name}"]`)
    await row(names[0]).click()
    await page.locator('.diff-viewer').waitFor()
    const current = () => page.evaluate(() => window.__shot.ui.getState().fileView.file)
    const atEdge = async (direction) => page.evaluate((dir) => {
      for (const el of document.querySelectorAll('.fv-body, .diff-split-col')) el.scrollTop = dir === 1 ? el.scrollHeight : 0
    }, direction)
    const wheel = async (delta, count = 1, target = '.fv-body', horizontal = false) => {
      for (let i = 0; i < count; i++) {
        await page.locator(target).first().dispatchEvent('wheel', { deltaY: delta, deltaX: horizontal ? delta * 2 : 0, bubbles: true, cancelable: true })
        await page.waitForTimeout(25)
      }
    }
    await page.evaluate(() => window.__shot.ui.getState().openModal({ kind: 'settings', page: 'files' }))
    const toggle = page.getByRole('checkbox', { name: /Pull between files/ })
    await toggle.uncheck()
    assert.equal(await page.getByRole('radio', { name: /Quick/ }).isDisabled(), true)
    await page.evaluate(() => window.__shot.ui.getState().closeModal())
    await atEdge(1); await wheel(40, 16); await page.waitForTimeout(600)
    assert.equal(await current(), names[0], 'disabled gesture must not switch files')
    assert.equal(await page.locator('.fv-file-pull').count(), 0)
    await page.evaluate(() => window.__shot.ui.getState().openModal({ kind: 'settings', page: 'files' }))
    await toggle.check()
    assert.equal(await page.getByRole('radio', { name: /Balanced/ }).getAttribute('aria-checked'), 'true')
    await page.evaluate(() => window.__shot.ui.getState().closeModal())
    await atEdge(1); await wheel(40, 10)
    await page.locator('.fv-file-pull.is-ready').waitFor()
    await page.evaluate(() => window.__shot.settings.getState().update((s) => ({ ...s, elasticFileNavigation: false })))
    await page.waitForTimeout(600)
    assert.equal(await current(), names[0], 'disabling during a pull must cancel pending navigation')
    assert.equal(await page.locator('.fv-file-pull').count(), 0)
    await page.evaluate(() => window.__shot.settings.getState().update((s) => ({ ...s, elasticFileNavigation: true })))
    await atEdge(1)
    await wheel(40, 2)
    assert.equal(await page.locator('.fv-file-pull').count(), 1)
    await page.waitForTimeout(600)
    assert.equal(await current(), names[0], 'short pull must cancel')
    await atEdge(1)
    await wheel(40, 16, '.fv-body', true)
    await page.waitForTimeout(600)
    assert.equal(await current(), names[0], 'horizontal scroll must not switch')
    await atEdge(-1)
    await wheel(40, 1)
    await atEdge(1)
    await wheel(40, 12)
    await page.waitForTimeout(600)
    assert.equal(await current(), names[0], 'momentum at edge must not switch')
    await wheel(40, 16)
    await page.locator('.fv-file-pull.is-ready').waitFor()
    await page.screenshot({ path: '/tmp/geminio-elastic-ready.png' })
    await page.waitForTimeout(650)
    assert.equal(await current(), names[1], 'forward pull must open next file')
    await page.locator('.diff-viewer').waitFor()
    // Real native wheel input must scroll immediately during the tail guard.
    await page.locator('.fv-body').hover()
    const startTop = await page.locator('.fv-body').evaluate((el) => el.scrollTop)
    await page.mouse.wheel(0, 120)
    await page.waitForTimeout(80)
    assert.ok(await page.locator('.fv-body').evaluate((el) => el.scrollTop) > startTop, 'new file must remain scrollable during handoff')
    await atEdge(1)
    await wheel(40, 24)
    assert.equal(await current(), names[1], 'wheel tail must not skip another file')
    await page.waitForTimeout(650)
    await atEdge(-1)
    await wheel(-40, 16)
    await page.waitForTimeout(650)
    assert.equal(await current(), names[0], 'backward pull must open previous file')
    await page.locator('.diff-viewer').waitFor()
    assert.ok(await page.locator('.fv-body').evaluate((el) => el.scrollTop > 100), 'previous file opens at its bottom')
    await page.waitForTimeout(650)
    await atEdge(-1); await wheel(-40, 8); await page.waitForTimeout(600)
    assert.equal(await current(), names[0], 'first file must not wrap')
    await page.getByRole('button', { name: 'Split', exact: true }).click()
    await page.locator('.diff-split-col').first().waitFor()
    await atEdge(1); await page.waitForTimeout(600); await wheel(40, 16, '.diff-split-col')
    await page.waitForTimeout(650)
    assert.equal(await current(), names[1], 'split diff can advance from column edge')
    await page.locator('.diff-split-col').first().hover()
    const splitTop = await page.locator('.diff-split-col').first().evaluate((el) => el.scrollTop)
    await page.mouse.wheel(0, 120)
    await page.waitForTimeout(80)
    assert.ok(await page.locator('.diff-split-col').first().evaluate((el) => el.scrollTop) > splitTop, 'split diff must remain scrollable during handoff')
    await row(names[3]).click(); await page.locator('.diff-viewer').waitFor(); await page.waitForTimeout(650)
    await atEdge(1); await wheel(40, 16, '.diff-split-col'); await page.waitForTimeout(650)
    assert.equal(await current(), names[4], 'staged list advances')
    assert.equal(await page.evaluate(() => window.__shot.ui.getState().fileView.source.staged), true)
    await page.waitForTimeout(650); await atEdge(1); await wheel(40, 8, '.diff-split-col'); await page.waitForTimeout(600)
    assert.equal(await current(), names[4], 'staged list must not cross into unstaged')
    await page.evaluate((p) => {
      const repo = window.__shot.repo.getState().repos[p]
      window.__shot.repo.getState().select(p, { type: 'commit', hash: repo.commits[0].hash })
      window.__shot.ui.getState().setFileView(null)
    }, repo)
    await row(names[0]).click(); await page.locator('.diff-viewer').waitFor(); await page.waitForTimeout(650)
    await atEdge(1); await wheel(40, 16, '.diff-split-col'); await page.waitForTimeout(650)
    assert.equal(await current(), names[1], 'commit files advance')
    console.log('PASS elastic: cancellation, horizontal wheel, momentum, forward/back, entry edge, tail guard, split, staging scope, commit files')
    await page.evaluate(() => window.__shot.ui.getState().openModal({ kind: 'settings', page: 'files' }))
    await page.getByRole('radio', { name: /Fast Light/ }).click()
    await toggle.uncheck()
    await page.evaluate(() => window.__shot.ui.getState().closeModal())
    console.log('PASS gesture settings: default balanced, toggle, active pull cancellation, preset choice; native scrolling after unified/split handoff')
    await app.evaluate(({ app }) => {
      globalThis.iconApplications = []
      const original = app.dock.setIcon.bind(app.dock)
      app.dock.setIcon = (image) => { globalThis.iconApplications.push(image.getSize()); return original(image) }
    })
    await page.evaluate(() => window.__shot.ui.getState().openModal({ kind: 'settings', page: 'themes' }))
    await page.getByRole('button', { name: 'Monogram', exact: true }).click()
    await page.getByRole('button', { name: 'Ocean', exact: true }).click()
    await page.waitForTimeout(700)
    assert.deepEqual(await page.evaluate(() => window.__shot.settings.getState().settings.appIcon), { style: 'monogram', color: 'ocean' })
    assert.ok((await app.evaluate(() => globalThis.iconApplications)).length >= 1, 'native Dock API must receive the new icon')
    await page.locator('.app-icon-picker').screenshot({ path: '/tmp/geminio-icon-picker.png' })
    await app.close(); app = null
    const saved = JSON.parse(await fs.readFile(join(userData, 'gitcito-settings.json'), 'utf8'))
    assert.equal(saved.elasticFileNavigation, false)
    assert.equal(saved.elasticFileNavigationFeel, 'fast')
    assert.deepEqual(saved.appIcon, { style: 'monogram', color: 'ocean' })
    app = await _electron.launch({ args: [join(ROOT, 'out/main/index.js'), '--shot', `--user-data-dir=${userData}`], cwd: ROOT })
    const restarted = await app.firstWindow(); await restarted.waitForFunction(() => window.__shot?.settings.getState().loaded)
    assert.deepEqual(await restarted.evaluate(() => window.__shot.settings.getState().settings.appIcon), saved.appIcon)
    assert.equal(await restarted.evaluate(() => window.__shot.settings.getState().settings.elasticFileNavigation), false)
    assert.equal(await restarted.evaluate(() => window.__shot.settings.getState().settings.elasticFileNavigationFeel), 'fast')
    console.log('PASS icon: live native Dock update, persistent choice, relaunch')
  } catch (err) {
    if (app) { const page = await app.firstWindow(); await page.screenshot({ path: '/tmp/geminio-feature-failure.png' }).catch(() => {}) }
    throw err
  } finally { if (app) await app.close(); await fs.rm(tmp, { recursive: true, force: true }) }
})().catch((err) => { console.error(err); process.exitCode = 1 })
