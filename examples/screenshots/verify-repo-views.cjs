// Native repo-switch regression: real repositories, isolated app settings.
// Run after npm run build: node examples/screenshots/verify-repo-views.cjs
const { _electron } = require('playwright')
const fs = require('node:fs/promises')
const { execFileSync } = require('node:child_process')
const { join } = require('node:path')
const assert = require('node:assert/strict')
const ROOT = join(__dirname, '../..')
;(async () => {
  const tmp = await fs.mkdtemp('/tmp/geminio-repo-views-')
  const paths = [join(tmp, 'a'), join(tmp, 'b')]
  const userData = join(tmp, 'settings')
  for (const [index, repo] of paths.entries()) {
    await fs.cp(join(ROOT, 'examples/playground/line-staging'), repo, { recursive: true })
    const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' })
    await fs.writeFile(join(repo, 'same.ts'), Array.from({ length: 220 }, (_, i) => `export const repo${index}Value${i} = ${i}`).join('\n'))
    git('add', '.'); git('-c', 'user.name=Demo', '-c', 'user.email=demo@example.com', 'commit', '-qm', `Repo ${index} baseline`)
    await fs.writeFile(join(repo, 'same.ts'), Array.from({ length: 220 }, (_, i) => `export const repo${index}Value${i} = ${i + 1000}`).join('\n'))
    git('add', '.'); git('-c', 'user.name=Demo', '-c', 'user.email=demo@example.com', 'commit', '-qm', `Repo ${index} changes`)
  }
  await fs.mkdir(userData)
  await fs.writeFile(join(userData, 'gitcito-settings.json'), JSON.stringify({ onboardingCompleted: true, autoFetchMinutes: 0, themeMode: 'dark', fileListView: 'path', profiles: [{ id: 'default', name: 'Demo', ai: { enabled: false } }], activeProfileId: 'default', tabs: paths.map((path, i) => ({ id: String(i), kind: 'repo', name: `Repo ${i ? 'B' : 'A'}`, repos: [{ path, name: `Repo ${i ? 'B' : 'A'}` }], activeRepoPath: path })), activeTabId: '0' }))
  await fs.writeFile(join(userData, 'gitcito-keychain.json'), JSON.stringify({ consent: 'declined', explained: true }))
  let app
  try {
    app = await _electron.launch({ args: [join(ROOT, 'out/main/index.js'), '--shot', '--background-test', `--user-data-dir=${userData}`], cwd: ROOT })
    const page = await app.firstWindow()
    page.setDefaultTimeout(15000)
    const errors = []
    page.on('pageerror', (e) => errors.push(e.message))
    await page.waitForFunction(() => window.__shot?.ready)
    for (const path of paths) await page.evaluate((p) => window.__shot.waitForRepo(p), path)
    await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.unmaximize(); w.setContentSize(1440, 900) })
    const switchTo = async (i) => {
      await page.locator('.tab-name').filter({ hasText: i ? 'Repo B' : 'Repo A' }).click()
      await page.waitForFunction((p) => window.__shot.ui.getState().activeRepoPath === p, paths[i])
    }
    const openCommit = async (i) => {
      await page.evaluate((p) => { const r = window.__shot.repo.getState(); r.select(p, { type: 'commit', hash: r.repos[p].commits[0].hash }) }, paths[i])
      await page.locator('.file-list [data-file-path="same.ts"]').click()
      await page.locator('.diff-viewer').waitFor()
    }
    const view = () => page.evaluate(() => window.__shot.ui.getState().fileView)
    await openCommit(0)
    const viewA = await view()
    await page.locator('.fv-body').evaluate((el) => { el.scrollTop = 500 })
    await switchTo(1)
    assert.equal(await view(), null, 'new repo starts with its graph')
    await openCommit(1)
    await page.getByRole('button', { name: 'File View', exact: true }).click()
    await page.locator('.file-content').waitFor()
    const viewB = await view()
    assert.ok((await page.locator('.fv-body').innerText()).includes('repo1Value'), 'same filename renders B content')
    await switchTo(0)
    await page.locator('.diff-viewer').waitFor()
    assert.deepEqual(await view(), viewA, 'A commit/file/mode restored')
    await page.waitForFunction(() => document.querySelector('.fv-body').scrollTop === 500)
    assert.ok((await page.locator('.fv-body').innerText()).includes('repo0Value'), 'same filename restores A content')
    await page.getByRole('button', { name: 'Split', exact: true }).click()
    await page.locator('.diff-split-col').first().waitFor()
    await page.locator('.diff-split-col').first().evaluate((el) => { el.scrollTop = 360 })
    await page.waitForTimeout(100)
    const splitPositions = await page.locator('.diff-split-col').evaluateAll((els) => els.map((el) => el.scrollTop))
    await switchTo(1)
    await page.locator('.file-content').waitFor()
    await switchTo(0)
    await page.locator('.diff-split-col').first().waitFor()
    await page.waitForFunction((expected) => [...document.querySelectorAll('.diff-split-col')].every((el, i) => el.scrollTop === expected[i]), splitPositions)
    await switchTo(1)
    await page.locator('.file-content').waitFor()
    assert.deepEqual(await view(), viewB, 'B commit/file/mode restored')
    await page.evaluate(() => window.__shot.ui.getState().setFileView(null))
    await page.locator('.graph-scroll').waitFor()
    await page.evaluate(() => window.__shot.ui.getState().setGraphFilter('Repo 1'))
    await switchTo(0)
    await page.locator('.diff-viewer').waitFor()
    assert.equal(await page.evaluate(() => window.__shot.ui.getState().graphFilter), '')
    await switchTo(1)
    assert.equal(await view(), null, 'closing B does not reopen it')
    assert.equal(await page.evaluate(() => window.__shot.ui.getState().graphFilter), 'Repo 1')
    console.log('PASS separate commits, identical filenames, modes, unified/split scroll, close and filters')

    // In-memory edits survive switching without writing anything to disk.
    await switchTo(0)
    await page.evaluate((p) => window.__shot.ui.getState().setFileView({ repoPath: p, file: 'same.ts', source: { type: 'tree' }, mode: 'file' }), paths[0])
    await page.locator('.file-content').waitFor()
    await page.locator('.fv-path').click({ button: 'right' })
    await page.getByText('Edit File', { exact: true }).click()
    const editor = page.locator('.fv-body textarea')
    await editor.waitFor()
    await editor.fill('unsaved text in repository A\n')
    await page.waitForFunction(() => window.__shot.ui.getState().editorDirty)
    await switchTo(1)
    assert.equal(await page.evaluate(() => window.__shot.ui.getState().editorDirty), false)
    await switchTo(0)
    await editor.waitFor()
    assert.equal(await editor.inputValue(), 'unsaved text in repository A\n')
    await page.waitForFunction(() => window.__shot.ui.getState().editorDirty)
    assert.ok((await fs.readFile(join(paths[0], 'same.ts'), 'utf8')).includes('repo0Value'), 'switching never saves a draft')
    await page.screenshot({ path: '/tmp/geminio-repo-views.png' })
    console.log('PASS unsaved editor text survives switching without disk writes')

    // The same sessions also follow repository chips inside a group.
    await page.evaluate((paths) => window.__shot.settings.getState().update((s) => ({ ...s, tabs: [{ id: 'group', kind: 'group', name: 'Both', repos: paths.map((path, i) => ({ path, name: `Repo ${i ? 'B' : 'A'}` })), activeRepoPath: paths[1] }], activeTabId: 'group' })), paths)
    assert.equal(await view(), null)
    await page.locator('.tab.in-group .tab-name').filter({ hasText: 'Repo A' }).click()
    await editor.waitFor()
    assert.equal(await editor.inputValue(), 'unsaved text in repository A\n')
    assert.deepEqual(errors, [])
    console.log('PASS group switching restores the same repo sessions; no renderer errors')
  } catch (err) {
    if (app) await (await app.firstWindow()).screenshot({ path: '/tmp/geminio-repo-views-failure.png' }).catch(() => {})
    throw err
  } finally { if (app) await app.close(); await fs.rm(tmp, { recursive: true, force: true }) }
})().catch((err) => { console.error(err); process.exitCode = 1 })
