// Exercise the live demo's renderer with a disposable repo and recorded editor argv.
const { _electron } = require('playwright')
const fs = require('node:fs/promises')
const { join } = require('node:path')
const assert = require('node:assert/strict')
const ROOT = join(__dirname, '../..')
;(async () => {
  const tmp = await fs.mkdtemp('/tmp/geminio-settings-')
  const repo = join(tmp, 'my repo'), userData = join(tmp, 'settings'), argv = join(tmp, 'argv'), cli = join(tmp, 'editor')
  await fs.cp(join(ROOT, 'examples/playground/line-staging'), repo, { recursive:true })
  await fs.mkdir(userData)
  await fs.writeFile(cli, `#!/bin/sh\nprintf '%s\\n' "$@" > '${argv}'\n`, { mode:0o755 })
  await fs.writeFile(join(userData, 'gitcito-settings.json'), JSON.stringify({ onboardingCompleted:true, autoFetchMinutes:0, themeMode:'dark', profiles:[{ id:'default', name:'Demo', ai:{enabled:false} }], activeProfileId:'default', editor:{ id:'vscode', name:'Visual Studio Code', command:cli, source:'cli' }, tabs:[{ id:'demo', kind:'repo', name:'Demo', repos:[{path:repo,name:'Demo'}], activeRepoPath:repo }], activeTabId:'demo' }))
  await fs.writeFile(join(userData, 'gitcito-keychain.json'), JSON.stringify({ consent:'declined', explained:true }))
  let app
  try {
    app = await _electron.launch({ args:[join(ROOT,'out/main/index.js'),'--shot', '--background-test',`--user-data-dir=${userData}`], cwd:ROOT })
    const page = await app.firstWindow(); page.setDefaultTimeout(20000)
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), false, 'validation window must stay hidden')
    const errors=[]; page.on('pageerror',e=>errors.push(e.message))
    await page.waitForFunction(()=>window.__shot?.ready)
    await page.evaluate(p=>window.__shot.waitForRepo(p),repo)
    await page.evaluate(()=>window.__shot.ui.getState().openModal({kind:'settings',page:'general'}))
    const search = page.getByRole('searchbox',{name:'Search settings…'})
    await search.fill('minimap')
    await page.locator('[data-settings-page="files"].selected').waitFor()
    await page.locator('.settings-search-hit').filter({hasText:/minimap/i}).first().waitFor()
    assert.ok(await page.locator('.settings-search-dim').count()>5)
    assert.equal(await search.inputValue(),'minimap')
    await page.screenshot({path:'/tmp/geminio-settings-search.png'})
    assert.equal(await search.evaluate(el => getComputedStyle(el).boxShadow), 'none')
    const heading = await page.locator('.settings-heading').boundingBox(), field = await page.locator('.settings-search').boundingBox()
    assert.ok(Math.abs((heading.x + heading.width / 2) - (field.x + field.width / 2)) < 2)
    await page.evaluate(() => window.__shot.settings.getState().update(s => ({...s,themeMode:'light',appThemeId:'geminio'})))
    await page.waitForTimeout(200)
    await page.screenshot({path:'/tmp/geminio-settings-search-light.png'})
    await search.fill('line thickness')
    await page.locator('[data-settings-page="themes"].selected').waitFor()
    await page.locator('.theme-tab.active').filter({hasText:'Graph'}).waitFor()
    await search.fill('protected branches')
    await page.locator('[data-settings-page="repository"].selected').waitFor()
    await page.locator('.repo-settings-tabs .active').filter({hasText:'General'}).waitFor()
    await search.fill('vscode')
    await page.locator('[data-settings-page="general"].selected').waitFor()
    await search.fill('GitLab')
    await page.locator('[data-settings-page="integrations"].selected').waitFor()
    await page.locator('.remote-tab.active').filter({hasText:'GitLab'}).waitFor()
    await search.fill('nothingmatchesxyzzzz')
    await page.locator('.settings-search-empty').waitFor()
    await search.press('Escape')
    assert.equal(await page.locator('.settings-search-dim').count(),0)
    await page.locator('.settings').waitFor()
    await page.evaluate(p=>{ window.__shot.ui.getState().closeModal(); const state=window.__shot.repo.getState(); state.select(p,{type:'commit',hash:state.repos[p].commits[0].hash}) },repo)
    await page.locator('.file-list [data-file-path="README.md"]').click()
    await page.locator('.fv-open-editor').click()
    for(let i=0;i<50;i++){try{await fs.access(argv);break}catch{await page.waitForTimeout(50)}}
    assert.deepEqual((await fs.readFile(argv,'utf8')).trim().split('\n'),[repo,'-g',join(repo,'README.md')])
    await page.locator('.fv-header').screenshot({path:'/tmp/geminio-editor-shortcut.png'})
    await page.locator('.file-list [data-file-path="README.md"]').click({button:'right'})
    assert.equal(await page.getByText('Open with Default App',{exact:true}).count(),0)
    await page.getByText('Open in Visual Studio Code',{exact:true}).waitFor()
    assert.deepEqual(errors,[])
    console.log('PASS settings search: matching copy, dimmed navigation, nested tabs, empty result, Escape; editor button: repository + real file argv; no duplicate default-app menu')
  } catch(err){if(app)await(await app.firstWindow()).screenshot({path:'/tmp/geminio-settings-failure.png'}).catch(()=>{});throw err}
  finally {if(app)await app.close();await fs.rm(tmp,{recursive:true,force:true})}
})().catch(err=>{console.error(err);process.exitCode=1})
