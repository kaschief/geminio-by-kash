// Real Electron fullscreen and missing-folder recovery checks. Run after build.
const { _electron } = require('playwright')
const fs = require('node:fs/promises')
const { join } = require('node:path')
const assert = require('node:assert/strict')
const ROOT = join(__dirname, '../..')
;(async () => {
  const tmp = await fs.mkdtemp('/tmp/geminio-startup-')
  const valid = join(tmp, 'valid')
  const missing = join(tmp, 'missing')
  const recovered = join(tmp, 'relocated')
  const userData = join(tmp, 'settings')
  await fs.cp(join(ROOT, 'examples/playground/line-staging'), valid, { recursive: true })
  await fs.cp(valid, recovered, { recursive: true })
  await fs.mkdir(userData)
  await fs.writeFile(join(userData, 'gitcito-settings.json'), JSON.stringify({ onboardingCompleted: true, autoFetchMinutes: 0, themeMode: 'dark', profiles: [{ id: 'default', name: 'Demo', ai: { enabled: false } }], activeProfileId: 'default', tabs: [{ id: 'valid', kind: 'repo', name: 'Valid Repo', repos: [{ path: valid, name: 'Valid Repo' }], activeRepoPath: valid }, { id: 'missing', kind: 'repo', name: 'Moved Repo', repos: [{ path: missing, name: 'Moved Repo' }], activeRepoPath: missing }], activeTabId: 'valid' }))
  await fs.writeFile(join(userData, 'gitcito-keychain.json'), JSON.stringify({ consent: 'declined', explained: true }))
  let app
  try {
    app = await _electron.launch({ args: [join(ROOT, 'out/main/index.js'), '--shot', `--user-data-dir=${userData}`], cwd: ROOT })
    const page = await app.firstWindow()
    page.setDefaultTimeout(15000)
    const errors = []
    page.on('pageerror', (e) => errors.push(e.message))
    await page.waitForFunction(() => window.__shot?.ready)
    await page.waitForFunction((p) => window.__shot.repo.getState().repos[p]?.missingFolder, missing)
    assert.deepEqual(await page.evaluate(() => window.__shot.ui.getState().toasts.filter((t) => t.kind === 'error')), [], 'background missing tab must not toast')
    assert.equal(await page.locator('.workspace-switcher').count(), 0)
    assert.equal(await page.locator('.app-home-mark').innerText(), '')
    assert.ok((await page.locator('.app-home-mark').boundingBox()).width <= 32)
    assert.equal(await page.locator('.titlebar').evaluate((el) => getComputedStyle(el).paddingLeft), '78px')
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setFullScreen(true))
    await page.waitForFunction(() => document.querySelector('.titlebar').classList.contains('fullscreen'))
    assert.equal(await page.locator('.titlebar').evaluate((el) => getComputedStyle(el).paddingLeft), '6px')
    await page.locator('.titlebar').screenshot({ path: '/tmp/geminio-titlebar-fullscreen.png' })
    await page.reload()
    await page.waitForFunction(() => window.__shot?.ready && document.querySelector('.titlebar')?.classList.contains('fullscreen'))
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setFullScreen(false))
    await page.waitForFunction(() => !document.querySelector('.titlebar').classList.contains('fullscreen'))
    assert.equal(await page.locator('.titlebar').evaluate((el) => getComputedStyle(el).paddingLeft), '78px')
    await page.locator('.app-home-mark').click()
    assert.equal(await page.evaluate(() => window.__shot.ui.getState().missionOpen), true)
    await page.locator('.tab-name').filter({ hasText: 'Moved Repo' }).click()
    await page.locator('.missing-repository').waitFor()
    assert.ok((await page.locator('.missing-repository').innerText()).includes(missing))
    await page.getByRole('button', { name: 'Retry', exact: true }).click()
    await page.waitForTimeout(300)
    assert.deepEqual(await page.evaluate(() => window.__shot.ui.getState().toasts.filter((t) => t.kind === 'error')), [])
    console.log('PASS compact mark, no workspace dropdown, native fullscreen enter/reload/exit, quiet missing-folder startup')
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, recovered)
    await page.getByRole('button', { name: 'Locate…', exact: true }).click()
    await page.waitForFunction((path) => window.__shot.settings.getState().activeRepo()?.path === path, recovered)
    await page.evaluate((path) => window.__shot.waitForRepo(path), recovered)
    assert.equal(await page.locator('.missing-repository').count(), 0)
    assert.ok(await page.locator('.graph-scroll').count())
    await page.evaluate(() => window.__shot.ui.getState().openModal({ kind: 'settings', page: 'workspaces' }))
    await page.locator('.settings-workspace-list').waitFor()
    assert.deepEqual(errors, [])
    console.log('PASS locate reconnects saved tab; workspace manager remains available in Settings')
  } catch (err) {
    if (app) await (await app.firstWindow()).screenshot({ path: '/tmp/geminio-startup-failure.png' }).catch(() => {})
    throw err
  } finally {
    if (app) { await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]?.setFullScreen(false)).catch(() => {}); await app.close() }
    await fs.rm(tmp, { recursive: true, force: true })
  }
})().catch((err) => { console.error(err); process.exitCode = 1 })
